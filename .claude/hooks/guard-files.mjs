// PreToolUse guard for file tools (Read, Grep, Edit, Write, MultiEdit, NotebookEdit): keeps secrets
// and customer data out of reach and refuses edits that break the rules in CLAUDE.md.
// Content rules only look at lines the edit adds, so existing code never blocks an unrelated edit.

import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { ask, deny, isSensitivePath, projectDir, relPath, runGuard, SENSITIVE_HINT } from "./lib.mjs";

const CODE = /\.(ts|tsx|js|jsx|mjs|cjs)$/;
const TEST = /(\.test\.(ts|tsx|js)$)|(^|\/)__tests__\//;

const GENERATED = [
  [/^(infra\/)?package-lock\.json$/, "Lockfiles change only through npm install/uninstall."],
  [/^(\.next|out|node_modules|infra\/node_modules|infra\/cdk\.out|coverage)\//, "Build output and dependencies are generated."],
  [/(^|\/)next-env\.d\.ts$|\.tsbuildinfo$/, "This file is generated by Next.js / TypeScript."],
];

const HARD_SECRETS = [
  /\b(AKIA|ASIA)[0-9A-Z]{16}\b/,
  /-----BEGIN [A-Z ]*PRIVATE KEY-----/,
  /\b(ghp_[A-Za-z0-9]{36}|github_pat_\w{20,}|xox[abprs]-[\w-]{10,}|sk-ant-[\w-]{20,}|sk_live_\w{10,})/,
];
const SECRET_ASSIGNMENT =
  /\b(secret|password|passwd|api_?key|access_?key|secret_?key|hash_?secret|app_?secret|client_?secret|private_?key|key1|key2|token)\w*["']?\s*[:=]\s*["'`][^"'`\s]{8,}["'`]/i;
const PUBLIC_SECRET = /\bNEXT_PUBLIC_\w*(SECRET|PASSWORD|PRIVATE|TOKEN|HASH|_KEY\b)/;

const LOG_CALL = /\b(log\.(info|warn|error)|console\.(log|info|warn|error|debug|trace))\s*\(/g;
const PII_KEYS =
  "customer|name|phone|email|address|shippingAddress|street|ward|note|accessToken|token|attribution|ip|userAgent|headers|authorization|cookie|password|secret|body|order|input|payload|raw|req|request";
const PII_ARG = new RegExp(`(^|[{,(\\s])\\s*(\\.\\.\\.\\s*)?(${PII_KEYS})\\s*(?=[,}:)]|$)`, "m");
const PII_MEMBER = /\.(customer|phone|email|shippingAddress|accessToken|attribution|userAgent|note|street|ward)\b|\bheaders\.get\s*\(/;

const SERVER_ONLY =
  /^(@\/lib\/(config|repo|orders|payments|tiktok|notify|events|admin-auth|data|media|cdn|http|log|rate-limit|feeds)(\/.*)?|node:.*|@aws-sdk\/.*|fs|path|crypto|child_process)$/;

/** File content after the edit, or null when it cannot be reconstructed. */
function contentAfter(tool, input, file) {
  if (tool === "Write") return String(input.content ?? "");
  if (tool === "NotebookEdit" || !existsSync(file)) return null;
  let text = readFileSync(file, "utf8");
  const edits = tool === "MultiEdit" ? (input.edits ?? []) : [input];
  for (const e of edits) {
    if (e.old_string == null || !text.includes(e.old_string)) return null;
    text = e.replace_all ? text.split(e.old_string).join(e.new_string ?? "") : text.replace(e.old_string, () => e.new_string ?? "");
  }
  return text;
}

/** Lines the edit introduces (present after, not before). */
function addedLines(tool, input, file, after) {
  const count = (lines) => lines.reduce((m, l) => m.set(l, (m.get(l) ?? 0) + 1), new Map());
  let before = "";
  let now = after ?? "";
  if (tool === "Edit" || tool === "MultiEdit") {
    const edits = tool === "MultiEdit" ? (input.edits ?? []) : [input];
    before = edits.map((e) => e.old_string ?? "").join("\n");
    now = edits.map((e) => e.new_string ?? "").join("\n");
  } else if (tool === "Write" && existsSync(file)) {
    before = readFileSync(file, "utf8");
  } else if (tool === "NotebookEdit") {
    now = String(input.new_source ?? "");
  }
  const old = count(before.split(/\r?\n/).map((l) => l.trim()));
  return now
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => {
      if (!l) return false;
      const left = old.get(l) ?? 0;
      if (left > 0) {
        old.set(l, left - 1);
        return false;
      }
      return true;
    });
}

/** Arguments of every log/console call in `text`, with the source they span. */
function logCalls(text) {
  const calls = [];
  for (const match of text.matchAll(LOG_CALL)) {
    let depth = 1;
    let i = match.index + match[0].length;
    const start = i;
    while (i < text.length && depth > 0 && i - start < 4000) {
      const c = text[i];
      if (c === '"' || c === "'") {
        const close = text.indexOf(c, i + 1);
        i = close < 0 ? text.length : close;
      } else if (c === "(") depth++;
      else if (c === ")") depth--;
      i++;
    }
    calls.push({ callee: match[1], source: text.slice(match.index, i), args: text.slice(start, i - 1) });
  }
  return calls;
}

const stripQuoted = (s) => s.replace(/"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*'/g, '""');

function importsOf(text) {
  const out = [];
  for (const m of text.matchAll(/^\s*import\s+([\s\S]*?)\s+from\s+["']([^"']+)["']/gm)) {
    const clause = m[1].trim();
    const typeOnly =
      /^type\s/.test(clause) ||
      (/^\{[\s\S]*\}$/.test(clause) &&
        clause.slice(1, -1).split(",").map((s) => s.trim()).filter(Boolean).every((s) => s.startsWith("type ")));
    out.push({ line: m[0].trim(), specifier: m[2], typeOnly });
  }
  return out;
}

function checkContent(rel, tool, input, file) {
  const after = contentAfter(tool, input, file);
  const added = addedLines(tool, input, file, after);
  if (!added.length) return;
  const addedText = added.join("\n");
  const isCode = CODE.test(rel);
  const isTest = TEST.test(rel);
  const inSrc = rel.startsWith("src/");

  if (HARD_SECRETS.some((re) => re.test(addedText))) deny("The edit adds what looks like a real credential. Secrets come from env / Secrets Manager only.");
  if (isCode && !isTest && SECRET_ASSIGNMENT.test(addedText)) {
    deny("The edit hard-codes a secret-like value. Read it from config (env locally, Secrets Manager on AWS).");
  }
  if (PUBLIC_SECRET.test(addedText)) deny("NEXT_PUBLIC_* variables are inlined into the browser bundle; never put a secret in one.");
  if (rel === ".env.example") {
    const filled = added.filter((l) => /^[A-Z0-9_]*(SECRET|KEY|PASSWORD|TOKEN|ACCESS)[A-Z0-9_]*=\S/.test(l) && !/=change-me$/.test(l));
    if (filled.length) deny(".env.example is committed: leave secret values empty.");
  }

  if (isCode) {
    if (/@ts-(ignore|nocheck)\b/.test(addedText)) deny("Fix the type error instead of adding @ts-ignore / @ts-nocheck.");
    if (added.some((l) => /^(\/\/|\/\*)\s*eslint-disable(?!-next-line|-line)/.test(l))) {
      deny("No file-wide eslint-disable. Fix the lint error, or disable one rule on one line with a reason.");
    }
  }
  if (isTest && /\b(it|test|describe)\.(only|skip)\s*\(|\bx(it|describe)\s*\(/.test(addedText)) {
    deny("Don't skip or focus tests. Make them pass, or tell the user why an expectation is wrong.");
  }

  // Does the edit add any line of `source`? Lines need real content, so an added "});" doesn't tie
  // the edit to every call that contains one.
  const meaningful = (l) => l.length >= 6 && /[A-Za-z]/.test(l);
  const touches = (source) => {
    const lines = source.split(/\r?\n/).map((l) => l.trim()).filter(meaningful);
    return added.filter(meaningful).some((a) => lines.some((l) => a.includes(l) || l.includes(a)));
  };

  if (inSrc && isCode && !isTest && after != null) {
    for (const call of logCalls(after)) {
      if (!touches(call.source)) continue;
      if (call.callee.startsWith("console") && rel !== "src/lib/log.ts") {
        deny("Use `log` from src/lib/log.ts (structured JSON logs) instead of console.* in src/.");
      }
      const args = stripQuoted(call.args);
      if (PII_ARG.test(args) || PII_MEMBER.test(args)) {
        deny(
          `This log call may write personal data or a whole object: ${call.source.replace(/\s+/g, " ").slice(0, 160)}. ` +
            "Log ids, counts, statuses and amounts only (CLAUDE.md invariant 7).",
        );
      }
    }

    const isClient = /^(\s*(\/\/[^\n]*|\/\*[\s\S]*?\*\/))*\s*["']use client["']/.test(after);
    if (isClient) {
      const directiveAdded = added.some((l) => /^["']use client["']/.test(l));
      for (const imp of importsOf(after)) {
        if (imp.typeOnly || !SERVER_ONLY.test(imp.specifier)) continue;
        if (directiveAdded || touches(imp.line)) {
          deny(`"use client" file imports server-only "${imp.specifier}" (CLAUDE.md invariant 12). Use \`import type\` or pass data as props.`);
        }
      }
    }

    if (/dangerouslySetInnerHTML/.test(addedText) && !/^src\/(components\/seo\.tsx|app\/\[lang\]\/layout\.tsx)$/.test(rel)) {
      deny("No dangerouslySetInnerHTML outside the JSON-LD and theme script (CLAUDE.md invariant 14).");
    }
  }

  if (rel.startsWith("infra/") && /RemovalPolicy\.DESTROY|deletionProtection:\s*false|pointInTimeRecoveryEnabled:\s*false|autoDeleteObjects:\s*true/.test(addedText)) {
    ask("This edit weakens data retention in the production stack (DESTROY, no deletion protection, no PITR or auto-delete).");
  }
}

await runGuard(async (input) => {
  const tool = input.tool_name;
  const ti = input.tool_input ?? {};
  const root = projectDir(input);

  if (tool === "Grep") {
    const target = [ti.path, ti.glob].filter(Boolean).join(" ");
    if (target && (isSensitivePath(ti.path ?? "") || /\.env(?!\.example)|\.data\b/.test(target))) {
      deny(`Searching ${target} is not allowed. ${SENSITIVE_HINT}`);
    }
    return;
  }

  const file = ti.file_path ?? ti.notebook_path;
  if (!file) return;
  const abs = path.resolve(root, file);
  if (isSensitivePath(abs)) deny(`${path.basename(abs)} is protected. ${SENSITIVE_HINT}`);
  if (tool === "Read") return;

  // Another session's worktree under .claude/worktrees belongs to that session.
  const worktree = abs.replace(/\\/g, "/").match(/^(.*\/\.claude\/worktrees\/[^/]+)(\/|$)/i);
  const rootNormal = root.replace(/\\/g, "/").toLowerCase();
  if (worktree && !rootNormal.startsWith(worktree[1].toLowerCase())) {
    deny(`${worktree[1]} is another session's git worktree. Edit files in this session's checkout only.`);
  }

  const rel = relPath(abs, root);
  if (!rel) return;
  for (const [re, why] of GENERATED) if (re.test(rel)) deny(`${rel}: ${why}`);
  checkContent(rel, tool, ti, abs);
});
